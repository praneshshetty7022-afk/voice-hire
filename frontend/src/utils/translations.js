/**
 * Returns translation object for given language code.
 * Falls back transparently to English for any missing keys via Proxy.
 */
export const getTranslation = (lang = 'en') => {
  const code = (lang || 'en').split('-')[0].toLowerCase()
  const targetDict = TRANSLATIONS[code] || TRANSLATIONS.en

  return new Proxy(targetDict, {
    get(target, prop) {
      if (prop in target) {
        return target[prop]
      }
      if (TRANSLATIONS.en && prop in TRANSLATIONS.en) {
        return TRANSLATIONS.en[prop]
      }
      return ''
    },
  })
}
